"""Markdown reporter — human-readable report for developers."""

from __future__ import annotations

from ..models import ScanResult, Severity


def render_markdown(result: ScanResult) -> str:
    """Render a scan result as Markdown."""
    lines: list[str] = []

    lines.append("# PHP Security Audit Report")
    lines.append("")
    lines.append(f"**Project:** `{result.project_path}`")
    lines.append(f"**Scan time:** {result.scan_time}")
    lines.append("**Tool:** php-security-audit-toolkit v0.1.0")
    lines.append("")

    # Summary
    lines.append("## Summary")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("|--------|-------|")
    lines.append(f"| Files scanned | {result.files_scanned} |")
    lines.append(f"| Checks completed | {result.checks_completed} |")
    lines.append(f"| Checks skipped | {result.checks_skipped} |")
    lines.append(f"| Total findings | {result.total_findings} |")
    lines.append("")

    # Findings by severity
    summary = result.findings_by_severity
    lines.append("### Findings by Severity")
    lines.append("")
    lines.append("| Severity | Count |")
    lines.append("|----------|-------|")
    for sev in [Severity.CRITICAL, Severity.HIGH, Severity.MEDIUM, Severity.LOW, Severity.INFO]:
        count = summary.get(sev.value, 0)
        lines.append(f"| {sev.value} | {count} |")
    lines.append("")

    # Skipped checks
    skipped = [c for c in result.checks if c.status.value in ("SKIPPED", "INCONCLUSIVE")]
    if skipped:
        lines.append("### Skipped Checks")
        lines.append("")
        for c in skipped:
            lines.append(f"- **{c.name}**: {c.message}")
        lines.append("")

    # Findings
    if result.findings:
        lines.append("## Findings")
        lines.append("")

        for f in result.findings:
            if f.suppressed:
                continue

            lines.append(f"### [{f.severity.value}] {f.rule_id}: {f.title}")
            lines.append("")
            lines.append(f"**File:** `{f.file}:{f.line}`" if f.line > 0 else f"**File:** `{f.file}`")
            lines.append(f"**Confidence:** {f.confidence.value}")
            lines.append(f"**Detection method:** {f.detection_method}")
            if f.manual_verification_required:
                lines.append("**Manual verification required:** Yes")
            lines.append("")
            lines.append(f"**Description:** {f.description}")
            lines.append(f"**Evidence:** `{f.evidence}`")
            lines.append(f"**Impact:** {f.impact}")
            lines.append(f"**Remediation:** {f.remediation}")
            if f.references:
                lines.append("**References:**")
                for ref in f.references:
                    lines.append(f"- {ref}")
            lines.append("---")
            lines.append("")

    # Suppressed findings
    suppressed = [f for f in result.findings if f.suppressed]
    if suppressed:
        lines.append("## Suppressed Findings")
        lines.append("")
        for f in suppressed:
            lines.append(f"- **{f.rule_id}** `{f.file}` — {f.suppression_reason}")
        lines.append("")

    # Limitations
    lines.append("## Limitations")
    lines.append("")
    lines.append(
        "This report is generated by automated pattern-based and configuration checks. "
        "It does not constitute a comprehensive security assessment. "
        "A clean scan does not prove that the application is secure. "
        "Pattern-based findings require manual verification to confirm exploitability."
    )

    return "\n".join(lines)
